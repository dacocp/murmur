#!/usr/bin/env python3
"""Build the independent reader companion; never package the Murmur runtime."""

import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import tarfile


HERE = Path(__file__).resolve().parent
ASSETS = ("app.html", "app.js", "app.css", "api.js", "compose.js")


def digest(content):
    return hashlib.sha256(content).hexdigest()


def encoded(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def versioned_html(template, assets):
    """A fresh document must not execute an older cached script or stylesheet."""
    seen = set()
    references = re.compile(r'''(?P<prefix>\b(?:src|href)\s*=\s*)(?P<quote>["'])(?P<name>[A-Za-z0-9_.-]+)(?:\?[^"'<>]*)?(?P=quote)''')

    def replace(match):
        name = match["name"]
        if name not in assets:
            return match[0]
        seen.add(name)
        return match["prefix"] + match["quote"] + name + "?v=" + digest(assets[name]) + match["quote"]

    result = references.sub(replace, template.decode("utf-8"))
    missing = assets.keys() - seen
    if missing:
        raise ValueError("App document must reference every required asset: " + ", ".join(sorted(missing)))
    return result.encode("utf-8")


def package(source=HERE, output=None):
    source = Path(source)
    output = Path(output) if output else source / "dist"
    inputs = {}
    for name in ("plugin.json", "launcher.js", "build.py", *ASSETS):
        path = source / name
        if path.is_symlink() or not path.is_file():
            raise ValueError("Missing regular preview source: " + name)
        inputs[name] = path.read_bytes()
    # Reuse the console's exact pending-send authority, never a second copy of
    # its storage/lock rules. Keep both source and generated bytes in provenance.
    model = source.parent / "webapp" / "model.js"
    if model.is_symlink() or not model.is_file():
        raise ValueError("Missing regular operator model: " + str(model))
    inputs["../webapp/model.js"] = model.read_bytes()
    inputs["operator-model.js"] = (b"(function(scope){const module={exports:{}};\n" +
                                   inputs["../webapp/model.js"] +
                                   b"\nscope.MurmurOperatorModel=module.exports;})(globalThis);\n")
    inputs["source/app.html"] = inputs["app.html"]
    inputs["app.html"] = versioned_html(inputs["source/app.html"], {
        name: inputs[name] for name in (*ASSETS, "operator-model.js") if name != "app.html"
    })
    manifest = json.loads(inputs["plugin.json"])
    if (manifest.get("id") != "murmur-preview" or "server" in manifest
            or manifest.get("webapp") != {"bundle_path": "webapp/index.js"}
            or not re.fullmatch(r"\d+\.\d+\.\d+", manifest.get("version", ""))):
        raise ValueError("Expected the serverless murmur-preview manifest")
    try:
        revision = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=source, stderr=subprocess.DEVNULL, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        revision = "unknown"
    files = {name: digest(content) for name, content in sorted(inputs.items())}
    build = {"schema": 1, "plugin_id": manifest["id"], "version": manifest["version"],
             "revision": revision, "source_sha256": digest(encoded(files)), "inputs": files}
    entries = {"plugin.json": inputs["plugin.json"], "webapp/index.js": inputs["launcher.js"],
               "build.json": encoded(build)}
    entries.update({"public/app/" + name: inputs[name] for name in ASSETS})
    entries["public/app/operator-model.js"] = inputs["operator-model.js"]
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", filename="", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w") as archive:
            for name, content in sorted(entries.items()):
                entry = tarfile.TarInfo(name)
                entry.size, entry.mode, entry.mtime = len(content), 0o644, 0
                archive.addfile(entry, io.BytesIO(content))
    payload = buffer.getvalue()
    output.mkdir(parents=True, exist_ok=True)
    artifact = output / ("murmur-preview-" + manifest["version"] + ".tar.gz")
    artifact.write_bytes(payload)
    result = {**build, "archive": artifact.name, "archive_sha256": digest(payload),
              "archive_bytes": len(payload)}
    (output / "build-manifest.json").write_bytes(encoded(result))
    return artifact, result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Build output directory; default preview/dist")
    args = parser.parse_args()
    try:
        artifact, result = package(output=args.output)
    except (OSError, ValueError) as error:
        parser.exit(1, str(error) + "\n")
    print(json.dumps({"archive": str(artifact), "sha256": result["archive_sha256"],
                      "source_sha256": result["source_sha256"]}, sort_keys=True))


if __name__ == "__main__":
    main()
